/**
 * Competition logic: normalising participants to shared rules, seeding demo
 * bots, running every participant under identical conditions and ranking.
 *
 * Participants are configurations, never people. A "seeded_bot" is a
 * library strategy the product added; "you" is the creator's own entry;
 * "invited" is reserved for real multiplayer later and renders the same way.
 */

