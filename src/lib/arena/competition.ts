export interface Standing {
  participant: CompetitionParticipant;
  rank: number;
  result: BacktestResult | null;
  score: number | null;
  error: string | null;
  color: string;
}

export const ARENA_COLORS = ["var(--series-1)", "var(--series-2)", "var(--series-3)", "var(--series-4)", "var(--series-5)"];

export function colorForIndex(i: number): string {
  return i < ARENA_COLORS.length ? ARENA_COLORS[i] : "var(--series-muted)";
}

/** Run every participant under the competition rules and rank by risk-adjusted score. */
export function computeStandings(competition: Competition, series: CandleSeries[]): Standing[] {
  const { rules } = competition;
  const runs = competition.participants.map((participant, i) => {
    try {
      const result = runBacktest(normaliseToRules(participant.config, rules), series, { start: rules.start, end: rules.end, label: participant.name });
      return { participant, result, score: riskAdjustedScore(result), error: null, color: colorForIndex(i) };
    } catch (err) {
      return { participant, result: null, score: null, error: err instanceof Error ? err.message : "Could not run.", color: colorForIndex(i) };
    }
  });
  const ranked = [...runs].sort((a, b) => {
    if (a.score === null && b.score === null) return (b.result?.metrics.totalReturnPct ?? -Infinity) - (a.result?.metrics.totalReturnPct ?? -Infinity);
    if (a.score === null) return 1;
    if (b.score === null) return -1;
    if (b.score !== a.score) return b.score - a.score;
    return (b.result?.metrics.totalReturnPct ?? 0) - (a.result?.metrics.totalReturnPct ?? 0);
  });
  return ranked.map((r, i) => ({ ...r, rank: i + 1 }));
}

export function describeRules(rules: CompetitionRules): string {
  const market = marketOf(rules.assets[0]);
  const ccy = MARKETS[market].currency;
  const symbols = rules.assets.map((a) => a.split(":")[1] ?? a).join(" + ");
  const brokerage = rules.feeFixed ? `${rules.feeFixed} ${ccy}/order, ` : "";
  return `${symbols} (${MARKETS[market].shortName}) · ${rules.timeframe} bars · ${ccy} ${rules.initialCapital.toLocaleString("en-AU")} each · ${brokerage}${rules.feeBps}bp fee, ${rules.slippageBps}bp slippage`;
}
